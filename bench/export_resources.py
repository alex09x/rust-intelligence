"""Writes site/resources.data.js from a measure_resources.py run (one JSON line per server and repository).

Usage: export_resources.py RESULTS_JSONL COMMIT DATE [OUT_JS]
"""
import json
import sys
from pathlib import Path

ORDER = ["serde", "tokio", "rust-analyzer", "bevy"]
METHODS = [
    "textDocument/definition", "textDocument/hover", "textDocument/typeDefinition", "textDocument/documentHighlight",
    "textDocument/references", "textDocument/completion", "textDocument/inlayHint", "textDocument/semanticTokens/full",
    "textDocument/documentSymbol", "textDocument/foldingRange",
]
KEEP = ["files", "requests", "errors", "ready_s", "rss_ready_mb", "peak_rss_mb", "cpu_startup_s", "cpu_work_s", "work_wall_s"]


def main():
    src, commit, date = sys.argv[1], sys.argv[2], sys.argv[3]
    out = Path(sys.argv[4] if len(sys.argv) > 4 else Path(__file__).resolve().parent.parent / "site" / "resources.data.js")
    runs = {}
    for line in Path(src).read_text().splitlines():
        if line.startswith("{"):
            r = json.loads(line)
            runs.setdefault(r["repo"], {})["ridx" if r["kind"] == "ridx" else "ra"] = r
    repos = []
    for name in [n for n in ORDER if n in runs] + sorted(set(runs) - set(ORDER)):
        pair = runs[name]
        if set(pair) != {"ridx", "ra"}:
            sys.exit(f"{name}: both ridx and ra runs are needed")
        lat = [[m.split("/", 1)[1], pair["ridx"]["lat_ms_p50_p95"][m], pair["ra"]["lat_ms_p50_p95"][m]] for m in METHODS]
        repos.append({"name": name, **{k: {key: pair[k][key] for key in KEEP} for k in ("ridx", "ra")}, "latency": lat})
    data = {"commit": commit, "date": date, "source": f"bench/published/{Path(src).name}", "repos": repos}
    out.write_text(
        "/* Generated by bench/export_resources.py; do not edit. */\n"
        f"window.RIDX_RESOURCES = {json.dumps(data, indent=1)};\n"
    )
    print(f"{out}: {len(repos)} repositories")


if __name__ == "__main__":
    main()
